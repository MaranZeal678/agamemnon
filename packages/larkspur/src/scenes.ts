/**
 * The runbook: what Larkspur's agents and sandboxes try to do, scripted so a
 * demo is repeatable. Every scene goes through the real broker / supervisor —
 * nothing here decides an outcome. `expect` is what Agamemnon SHOULD do, and
 * `npm run verify` fails if it doesn't.
 */

export type Group = "commerce" | "platform" | "sandbox";

export interface SceneResult {
  headline: string;
  /** Broker effects this run produced (ids). */
  effects: string[];
  /** Per-step statuses, compared against `expect`. */
  outcomes: string[];
  sandbox?: Array<{ label: string; result: SandboxExecutionResult; tainted?: boolean }>;
  notes?: string[];
}

export interface Scene {
  id: string;
  group: Group;
  title: string;
  actor: string;
  /** What the agent is trying to do, in its own (plausible) words. */
  intent: string;
  /** What could go wrong without a gate. */
  risk: string;
  /** Code shown for sandbox scenes. */
  code?: string;
  /** Expected per-step outcomes (effect status, or "ok" / "killed" for sandbox runs). */
  expect: string[];
  run(w: World): Promise<SceneResult>;
}

const P = (w: World, name: string) => {
  const p = w.broker.store.principal(name);
  if (!p) throw new Error(`principal ${name} missing`);
  return p;
};

async function agentEffects(w: World, agent: string, goal: string, steps: Array<{ operation: string; params: Record<string, unknown>; declared?: Record<string, unknown> }>, tenant?: string) {
  const task = w.broker.engine.startTask(P(w, agent), { goal, tenant });
  const views = [];
  for (const s of steps) views.push(await w.broker.engine.propose(P(w, agent), { taskId: task.id, operation: s.operation, params: s.params, declared: s.declared as any }));
  return { task, views };
}

const pg = (sql: string) => ({ operation: "postgres.sql", params: { connection: "larkspur", sql } });
const pgRead = (sql: string) => ({ operation: "postgres.query", params: { connection: "larkspur", sql } });

let seq = 0;
async function sandboxRun(w: World, opts: { label: string; tenant: string; grants: CapabilityFlag[]; code: string; context?: Record<string, unknown>; allowedDomains?: string[]; timeoutMs?: number; maxMemoryMb?: number; keep?: boolean }) {
  const id = `${opts.label.toLowerCase().replace(/[^a-z0-9]+/g, "-")}-${++seq}`;
  await w.supervisor.spawnSandbox({
    id,
    tenantId: opts.tenant,
    runtime: "quickjs-wasm",
    capabilities: { grants: opts.grants, allowedDomains: opts.allowedDomains, maxMemoryMb: opts.maxMemoryMb ?? 32, timeoutMs: opts.timeoutMs ?? 3000 },
  });
  const result = await w.supervisor.executeInSandbox(id, opts.code, opts.context ?? {});
  const tainted = w.supervisor.status(id).tainted;
  if (!opts.keep && w.supervisor.status(id).status !== "terminated") await w.supervisor.terminateSandbox(id);
  return { id, result, tainted };
}

const sbStatus = (r: SandboxExecutionResult) => (r.killed ? "killed" : r.success ? "ok" : "error");

